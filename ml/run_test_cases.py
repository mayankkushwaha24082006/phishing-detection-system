"""
run_test_cases.py
-----------------
Runs a fixed list of test URLs through the real detector and saves a
Markdown table to docs/test_cases.md (for your report).

Pass rules:
  - legitimate URL  -> must NOT be labelled "Phishing"
  - phishing URL    -> must be "Suspicious" or "Phishing"
  - invalid input   -> must be rejected with an error message
Some cases may fail. That is a real result: write it up as a limitation.

Run:  python ml/run_test_cases.py     (the server does not need to be running)
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))
import prediction
from feature_extraction import normalize_url

LEGIT = [
    "https://www.wikipedia.org", "https://github.com", "https://www.bbc.com/news",
    "https://stackoverflow.com/questions", "https://www.amazon.in",
    "https://www.iitd.ac.in", "https://docs.python.org/3/", "https://mail.google.com/mail/u/0/",
]
PHISH = [  # made-up patterns, not real sites
    "http://paypal.com@evil-site.xyz/secure",
    "http://192.168.10.5/login/verify.php",
    "http://secure-login.update.account-verify.example.co.in/signin?next=http://x.com",
    "http://paypal-secure-login-verify.xyz/webscr/update",
    "http://bit.ly/3abcXYZ",
    "http://login.microsoftonline.com.verify-account.top/signin",
    "http://www.sbi-netbanking-update.in:8080/confirm/password",
    "http://0x7f000001/admin/login",
]
INVALID = ["", "http:facebook.com", "ftp://example.com", "not a url", "https://" + "a" * 3000 + ".com"]

rows, passed, total = [], 0, 0


def record(group, url, expected, ok, label, score, prob):
    global passed, total
    total += 1
    passed += ok
    shown = url if len(url) <= 70 else url[:67] + "..."
    rows.append(f"| {group} | `{shown}` | {expected} | {label} | {score} | {prob} | {'PASS' if ok else 'FAIL'} |")


for url in LEGIT + PHISH:
    is_legit = url in LEGIT
    clean, _ = normalize_url(url)
    r = prediction.analyze(clean)
    ok = r["label"] != "Phishing" if is_legit else r["label"] in ("Suspicious", "Phishing")
    record("Legitimate" if is_legit else "Phishing pattern", url,
           "not Phishing" if is_legit else "Suspicious/Phishing",
           ok, r["label"], r["risk_score"], f"{r['model_probability']:.2f}")

for bad in INVALID:
    try:
        normalize_url(bad)
        record("Invalid input", bad, "rejected", False, "accepted!", "-", "-")
    except ValueError as err:
        record("Invalid input", bad if bad else "(empty)", "rejected", True, "rejected", "-", "-")

out = ROOT / "docs"
out.mkdir(exist_ok=True)
text = ("# Sample test cases (generated by ml/run_test_cases.py)\n\n"
        "| Group | URL | Expected | Actual | Risk | Model prob | Result |\n"
        "|---|---|---|---|---|---|---|\n" + "\n".join(rows) +
        f"\n\n**{passed} of {total} cases passed.**\n")
(out / "test_cases.md").write_text(text)
print(text)
print("Saved to", out / "test_cases.md")